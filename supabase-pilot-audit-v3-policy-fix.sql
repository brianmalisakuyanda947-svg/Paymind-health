-- PayMind Health v2.1.58 — audit insert-policy correction
-- Apply AFTER supabase-pilot-audit-v2.sql.
--
-- The audit spoof test showed that a client could still insert a record tagged
-- source='database_trigger'. PostgreSQL permissive policies are ORed together,
-- so every legacy INSERT / ALL policy must be removed before adding the
-- restrictive client-only INSERT policy.
--
-- This migration preserves/recreates the hospital-member SELECT policy.
-- It does not remove or change the database audit triggers.

begin;

alter table public.audit_logs enable row level security;

do $paymind$
declare
  policy_row record;
begin
  for policy_row in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = 'audit_logs'
      and cmd in ('INSERT', 'ALL')
  loop
    execute format(
      'drop policy %I on public.audit_logs',
      policy_row.policyname
    );
  end loop;
end;
$paymind$;

-- Recreate a scoped read policy. Keep audit rows visible only to members
-- of the same hospital.
drop policy if exists "members can read audit logs"
  on public.audit_logs;

create policy "members can read audit logs"
on public.audit_logs
for select
to authenticated
using (public.user_in_hospital(hospital_id));

-- The only authenticated INSERT path is for client-tagged activity.
-- Database-trigger entries are generated by a SECURITY DEFINER trigger and
-- must never be accepted from a regular authenticated client session.
drop policy if exists "members can insert audit logs"
  on public.audit_logs;

create policy "members can insert audit logs"
on public.audit_logs
for insert
to authenticated
with check (
  source = 'client'
  and event_type !~ '^db_'
  and user_id = auth.uid()
  and public.user_in_hospital(hospital_id)
);

commit;

-- Read-only verification: inspect every audit_logs policy and RLS state.
select
  c.relrowsecurity as rls_enabled,
  c.relforcerowsecurity as force_rls,
  p.policyname,
  p.permissive,
  p.roles,
  p.cmd,
  p.qual,
  p.with_check
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
left join pg_policies p
  on p.schemaname = n.nspname
 and p.tablename = c.relname
where n.nspname = 'public'
  and c.relname = 'audit_logs'
order by p.policyname;
